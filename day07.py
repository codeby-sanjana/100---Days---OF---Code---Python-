# Day 7 : PYTHON OPERATORS 
a = 15
b = 2

# Arithmetic Calculations
print(a + b)   # Output: 17
print(a - b)   # Output: 13
print(a * b)   # Output: 30
print(a / b)   # Output: 7.5
print(a // b)  # Output: 7  (Drops the decimal part)
print(a % b)   # Output: 1  (Returns the remainder)
print(a ** b)  # Output: 225 (15 raised to power of 2)
